public class Employeeee {
	
	private int id;
	private String name;
	private String department;
	private double salary;
	
	public Employeeee(int id, String name, String department, double salary) {
		this.id = id;
		this.name = name;
		this.department = department;
		this.salary = salary;
	}
	
	public int getid() {
		return id;
		
	}
	
	public String getname() {
		return name;
		
	}
	
	public String getdepartment() {
		return department;
	}
	
	public double getsalary() {
		return salary;
	}
}
	 
	
